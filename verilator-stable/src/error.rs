use snafu::Snafu;

/// Runtime port read/write error.
#[derive(Debug, Snafu)]
#[non_exhaustive]
pub enum VerilatorError {
    #[snafu(whatever, display("{message}"))]
    Whatever {
        message: String,
        #[snafu(source(from(Box<dyn std::error::Error>, Some)))]
        source: Option<Box<dyn std::error::Error>>,
    },
}
